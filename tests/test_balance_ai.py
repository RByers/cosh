import os
import sys
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "scripts"))
import balance_ai as B  # noqa: E402


def msg(body, trailers="Change-Id: I123\nReviewed-on: https://chromium-review.googlesource.com/c/chromium/src/+/1\n"):
    return f"Subject line\n\n{body}\n\n{trailers}"


class ClassifyTest(unittest.TestCase):
    def test_agent_trailer(self):
        self.assertEqual(B.classify(msg("Do a thing.", "Agent-Generated: true\nChange-Id: I1")), "agent")

    def test_tool_trailers(self):
        for t in ("Co-Authored-By: Gemini <noreply@google.com>", "Assisted-by: Gemini",
                  "Co-Authored-By: Claude Opus 4.8 (1M context) <noreply@anthropic.com>",
                  "Co-Authored-By: AI (Claude Opus 4.7 via Pi)", "Co-authored-by: Copilot <x@github.com>",
                  "AI-Model: gemini-3-flash"):
            self.assertEqual(B.classify(msg("Fix.", t + "\nChange-Id: I1")), "trailer", t)

    def test_people_and_bots_are_not_ai(self):
        for t in ("Co-authored-by: dependabot[bot] <x@github.com>", "Co-authored-by: Maksim Sadym <a@b.c>",
                  "Co-authored-by: Ai Nakamura <ai@example.com>", "Co-authored-by: Aidan Smith <a@b.c>"):
            self.assertIsNone(B.classify(msg("Fix.", t + "\nChange-Id: I1")), t)

    def test_trailer_only_counts_in_the_last_paragraph(self):
        # An upstream log inside an import CL.
        body = "Import puppeteer.\n\nUpstream commit:\n  Fix\n\nCo-authored-by: Copilot <x@y>"
        self.assertIsNone(B.classify(msg(body)))

    def test_phrases(self):
        for b in ("Generated with gemini-cli.", "This CL was initially AI generated, with human touch-ups.",
"Then refined with gemini-cli",
                  "Written by an AI agent and reviewed by me.", "#ai-assisted",
                  "[AI-Assisted] Rename the selector", "Developed with assistance from Anthropic's Claude.",
                  "Used Gemini CLI to do the conversions.", "Generated by Gemini. Prompts made by me.",
                  "This CL was generated by an AI agent and verified by the author.",
                  "Initial patchset generated by headless gemini-cli using:", "Initial port was AI-generated.",
                  "This CL is created with the use of Gemini CLI", "gemini-cli was used to expand test TODOs",
                  "(by gemini-cli)", "The script was mainly generated by gemini.",
                  "The initial version was generated by Cider Agent with the following prompt",
                  "This CL is prepared with gemini-cli", "Mostly vibe-coded with `gemini-cli`, which did well.",
                  "Note: AI assisted with fixing android build errors", "[Agent fix] Use GMock matchers"):
            self.assertEqual(B.classify(msg(b)), "phrase", b)

    def test_features_and_tooling_are_not_markers(self):
        for b in ("[AIM] Add a button to the omnibox.", "Show summaries generated by the Gemini API in the side panel.",
                  "Update .claude/settings.json for the agents directory.", "[AutofillAI] Fix a crash.",
                  "Add a GEMINI.md for //chrome/browser/ui.", "Launch the Gemini CLI to diagnose test failures.",
                  "Copilot: show the sidebar on startup.", "Pin a prebuilt gemini cli binary.",
                  "Tab titles are generated by Gemini when the user opts in.", "The summary made by AI is shown."):
            self.assertIsNone(B.classify(msg(b)), b)

    def test_campaign(self):
        self.assertEqual(B.classify(msg("This is an AI-generated dead TODOs removal. Please review.")), "campaign")

    def test_quoted_lines_dont_count(self):
        self.assertIsNone(B.classify(msg("Reland.\n\n> Generated with gemini-cli.\n> More.")))


if __name__ == "__main__":
    unittest.main()
