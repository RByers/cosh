AGENT_FILE = re.compile(r"(?:^|/)(?:AGENTS\.md|GEMINI\.md|CLAUDE\.md|SKILL\.md|\.gemini/|\.claude/|\.agents/)")


def agent_file_adoption():
    """{3-level dir: unix time of the first agent-instruction file added in it
    or below it (or in an ancestor, which applies to it too)}, and the raw
    list of (time, path)."""
    out = subprocess.run(["git", "-C", SHARED, "log", "--first-parent", "main", "--diff-filter=A", "--no-renames",
                          "--name-only", "--format=%x01%ct", "--since=2024-01-01", "--",
                          "*AGENTS.md", "*GEMINI.md", "*CLAUDE.md", "*SKILL.md", "*.gemini/*", "*.claude/*",
                          "*.agents/*"], capture_output=True, text=True, check=True,
                         env={**os.environ, "GIT_NO_LAZY_FETCH": "1"}).stdout
    adds = []
    for rec in out.split("\x01")[1:]:
        lines = [x for x in rec.splitlines() if x.strip()]
        ct = int(lines[0])
        for p in lines[1:]:
            if AGENT_FILE.search(p):
                adds.append((ct, p))
    return sorted(adds)


def dir_prefixes(path, depth=3):
    parts = path.split("/")[:-1]
    return ["/".join(parts[:k]) + "/" for k in range(0, min(depth, len(parts)) + 1)]


def did(use):
    """Draft event study by 3-level directory, for two treatments: the first
    agent-instruction file that applies to the directory (in it, below it to
    depth 3, or in an ancestor), and the first quarter its share of
    broad-marked CLs reached USAGE_SHARE. Controls: not-yet-treated and
    never-treated directories in the same quarter (stacked differences)."""
    import balance_analysis as A
    USAGE_SHARE, MIN_Q = 0.05, 20
    adds = agent_file_adoption()
    byd = defaultdict(list)
    for c in use:
        if c["d3"]:
            byd[c["d3"]].append(c)
    busy = {d for d, v in byd.items() if len(v) >= 400}
    # Treatment 1: files. A file at "a/b/X.md" applies to a/b/ and its subdirs;
    # at the root ("AGENTS.md") to everything, so it's left out as non-specific.
    t_file = {}
    for ct, p in adds:
        parts = p.split("/")[:-1]
        if not parts:
            continue
        pre = "/".join(parts[:3]) + "/"
        q = A.quarter(ct)
        for d in busy:
            if d.startswith(pre) or pre.startswith(d):
                if d not in t_file or q < t_file[d]:
                    t_file[d] = q
    # Treatment 2: usage.
    t_use, share = {}, defaultdict(dict)
    for d in busy:
        qq = defaultdict(lambda: [0, 0])
        for c in byd[d]:
            qq[c["q"]][0] += 1
            qq[c["q"]][1] += c["ai"]
        for q in sorted(qq):
            n, k = qq[q]
            share[d][q] = k / n
            if n >= MIN_Q and k / n >= USAGE_SHARE and d not in t_use:
                t_use[d] = q
    print(f"\n== Directories with >= 400 CLs since mid-2023: {len(busy)}; file-treated {len(t_file)}, "
          f"usage-treated (>= {USAGE_SHARE:.0%} broad-marked in a quarter of >= {MIN_Q} CLs) {len(t_use)}")
    # Does a file predict usage?
    both = set(t_file) & set(t_use)
    print(f"  file and usage: {len(both)}; file only: {len(set(t_file) - set(t_use))}; "
          f"usage only: {len(set(t_use) - set(t_file))}; neither: {len(busy - set(t_file) - set(t_use))}")
    qs = sorted({c["q"] for c in use})
    qi = {q: i for i, q in enumerate(qs)}
    lead = [qi[t_use[d]] - qi[t_file[d]] for d in both]
    if lead:
        print(f"  usage threshold minus file quarter (quarters), median {st.median(lead):+.1f}, "
              f"usage first in {sum(1 for x in lead if x < 0)}, same quarter {sum(1 for x in lead if x == 0)}, "
              f"file first in {sum(1 for x in lead if x > 0)}")
    # Marked share after the file vs matched not-yet-treated dirs in the same quarters.
    post = [share[d].get(q, 0) for d in t_file for q in qs if q >= t_file[d] and q >= "2025Q3"]
    never = [share[d].get(q, 0) for d in busy - set(t_file) for q in qs if q >= "2025Q3"]
    if post and never:
        print(f"  mean broad-marked share per dir-quarter from 2025 Q3: file-treated after the file "
              f"{st.mean(post):.1%} (n={len(post)}), never-file dirs {st.mean(never):.1%} (n={len(never)})")
    names = ["feedback (threads/exp)", "threads/100 lines", "h to first review", "interdiff share", "rounds",
             "reverted<30d", "newcomer"]
    met = dict(METRICS)
    met["newcomer"] = lambda c: float(c["ten"] is not None and c["ten"] < 1)
    # Directory-quarter means.
    dq = defaultdict(lambda: defaultdict(list))
    for d in busy:
        for c in byd[d]:
            for n in names:
                v = met[n](c)
                if v is not None:
                    dq[(d, c["q"])][n].append(v)
    mean = {k: {n: st.mean(v) for n, v in m.items() if len(v) >= 10} for k, m in dq.items()}
    for label, treat in (("agent-instruction file", t_file), ("usage >= 5% marked", t_use)):
        print(f"\n-- Event study, treatment = {label} (speculative). Each cell: treated dir minus the mean of "
              "not-yet/never-treated dirs that quarter, minus the same gap at rel -1. ± is 1.96 SE across dirs.")
        print(f"{'rel q':>5} {'dirs':>5} " + " ".join(f"{n[:13]:>14}" for n in names))
        rows = defaultdict(lambda: defaultdict(list))
        for d, tq in treat.items():
            t = qi[tq]
            gaps = {}
            for rel in range(-4, 5):
                if not 0 <= t + rel < len(qs):
                    continue
                q = qs[t + rel]
                ctl = [x for x in busy if x != d and (x not in treat or qi[treat[x]] > t + rel)]
                g = {}
                for n in names:
                    me = mean.get((d, q), {}).get(n)
                    cv = [mean[(x, q)][n] for x in ctl if n in mean.get((x, q), {})]
                    if me is not None and len(cv) >= 5:
                        g[n] = me - st.mean(cv)
                gaps[rel] = g
            base = gaps.get(-1, {})
            for rel, g in gaps.items():
                for n, v in g.items():
                    if n in base:
                        rows[rel][n].append(v - base[n])
        for rel in range(-4, 5):
            r = rows.get(rel, {})
            nd = max((len(v) for v in r.values()), default=0)
            cells = []
            for n in names:
                v = r.get(n, [])
                if len(v) >= 5:
                    m, lo, hi = ci(v)
                    cells.append(f"{m:+.3f}±{(hi - lo) / 2:.3f}".rjust(14))
                else:
                    cells.append(f"{'':>14}")
            print(f"{rel:>+5} {nd:>5} " + " ".join(cells))


