# Coding tools, which count wherever a phrase says the CL was made with them,
# and generic words (Gemini, AI, LLM, agent), which also name Chrome features
# ("summaries generated by Gemini") and so count only when the line opens by
# saying this CL or its code was made with them.
TOOL_SPECIFIC = (r"(?:gemini[- ]cli|gemini code assist|claude(?: code| (?:opus|sonnet|haiku)\b[\w .-]*)?|anthropic's claude"
                 r"|copilot|jules|cursor|codex|chatgpt|gpt-?\d[\w.]*|an? (?:ai|llm|coding) agent|ai agent|cider agent)")
TOOL_GENERIC = r"(?:gemini|an? (?:ai|llm)(?: (?:model|assistant|tool))?|ai|llm|an? agent|agents?)"
VERB = (r"(?:generated|written|created|authored|drafted|produced|implemented|made|developed|refined|fixed|converted"
        r"|prepared|vibe-?coded"
        r"|prototyped|assisted|identified|discovered|done)\s+(?:primarily |mostly |mainly |largely |initially "
        r"|partially |partly |entirely |fully |then )?(?:with|by|using|via|in)\s+(?:the help of |help from "
        r"|assistance from |the assistance of |the use of )?(?:google's |the |headless |an? )?[`'\"]?")
NOT_FEATURE = r"(?![\w-]| (?:api|apis|model|models|nano|in chrome|feature|button|panel|response|backend|service|server|app)\b)"
PHRASE = re.compile(r"\b" + VERB + TOOL_SPECIFIC + NOT_FEATURE, re.I)
PHRASE_GENERIC = re.compile(
    r"^\s*(?:(?:this|the|most of this|much of this|all of this|parts of this|initial|the initial) (?:cl|change|patch"
    r"|commit|code|fix|test|tests|refactor|conversion|migration|script|port|version|draft|implementation"
    r"|patch ?set)s?(?: (?:is|was|were|has been|have been))? )?"
    r"(?:(?:mostly|mainly|largely|partly|partially|initially|entirely|fully) )?" + VERB + TOOL_GENERIC
    + NOT_FEATURE, re.I)
TRAILER_AGENT = re.compile(r"^agent-generated:\s*(?:true|yes|1)\s*$", re.I)
# Co-author and assistance trailers naming an AI tool. dependabot and other
# bots, and people, don't match: the value must name a tool.
TRAILER_TOOL = re.compile(
    r"^(?:ai-model:\s*\S|(?:co-authored-by|assisted-by|generated-by|ai-assisted-by|tool):\s*"
    r"(?:ai(?:\s*\(|\s*$|\s+(?:agent|assistant)\b)|(?:an? )?(?:ai )?\(?(?:gemini|claude|copilot|jules|cursor|codex"
    r"|chatgpt|gpt-?\d|llm)\b))", re.I)
# "This CL is AI generated", "#ai-assisted", "[AI-Assisted] ...", "This is an
# AI-generated dead TODOs removal", "Gemini-CLI auto-fixes".
SELF = re.compile(
    r"#ai-assisted\b|^\s*\[(?:[\w ]*\]\s*\[)?ai[- ](?:assisted|generated)\]"
    r"|\b(?:this (?:cl|change|patch|commit) (?:is|was)|this is an?|cl (?:is|was)) (?:\w+ ){0,2}ai[- ](?:generated|assisted)\b"
    r"|^\s*ai[- ](?:generated|assisted)(?: development)?:"
    r"|\bgemini[- ]cli (?:auto-fixes|was in the driver's seat|prompt:)"
    r"|\b(?:used|using) (?:the )?(?:gemini[- ]cli|claude code|copilot|jules|codex|cursor)\b(?! (?:is|are|was|were|binary|bin|config))"
    r"|\bpassed to gemini[- ]cli\b"
    r"|\b(?:gemini[- ]cli|claude code|codex|jules|cursor|copilot) was used\b"
    r"|\(\s*(?:generated |written |identified )?by (?:gemini[- ]cli|claude code|codex|jules)\s*\)"
    r"|^\s*(?:the )?initial (?:port|version|patch ?set|draft|implementation|cl) (?:was|is) (?:\w+ )?ai[- ]generated"
    r"|^\s*(?:note: )?ai[- ]assisted (?:with|in)\b|^\s*\[agent fix\]", re.I)


# One bulk campaign (about 500 CLs from late 2025) that removes dead TODOs with
# an AI tool, all with the same sentence. Kept as its own rule so it can't
# dominate comparisons.
CAMPAIGN = re.compile(r"^This is an AI-generated dead TODOs removal\.", re.M)


def last_paragraph(msg):
    """The trailer block: the message's last paragraph."""
    paras = [p for p in re.split(r"\n\s*\n", msg.strip()) if p.strip()]
    return paras[-1] if paras else ""


def classify(msg):
    """The rule an AI marker in a commit message matches, or None.
    'campaign' (the bulk dead-TODO removals), 'agent' (Agent-Generated
    trailer), 'trailer' (an AI tool as co-author or assistant), 'phrase' (the
    text says the CL was made with an AI tool).
    Quoted lines ('> ...', as in reverts and relands) and trailers outside the
    last paragraph (an upstream log inside an import) don't count."""
    if CAMPAIGN.search(msg):
        return "campaign"
    tail = last_paragraph(msg).splitlines()
    if any(TRAILER_AGENT.match(line.strip()) for line in tail):
        return "agent"
    if any(TRAILER_TOOL.match(line.strip()) for line in tail):
        return "trailer"
    for line in msg.splitlines():
        if line.lstrip().startswith(">"):
            continue
        if PHRASE.search(line) or PHRASE_GENERIC.search(line) or SELF.search(line):
            return "phrase"
    return None


def matched_line(msg):
    for line in msg.splitlines():
        s = line.strip()
        if s.startswith(">"):
            continue
        if (TRAILER_AGENT.match(s) or TRAILER_TOOL.match(s) or PHRASE.search(s) or PHRASE_GENERIC.search(s)
                or SELF.search(s)):
            return s
    return ""


# Near misses for the hand check: AI words that the rules leave alone.
NEAR = re.compile(r"\b(?:gemini|claude|copilot|ai[- ]generated|ai[- ]assisted|llm|agent)\b", re.I)

REVIEWED_ON = re.compile(r"^Reviewed-on: https://chromium-review\.googlesource\.com/(?:c/)?(?:chromium/src/\+/)?(\d+)\s*$", re.M)


def git_messages(since="2024-01-01"):
    """[(sha, unix commit time, subject, body)] of main's first-parent history since `since`."""
    out = subprocess.run(["git", "-C", SHARED, "log", "--first-parent", f"--since={since}", "main",
                          "--format=%x01%x02%H %ct%n%B"], capture_output=True, text=True, check=True,
                         env={**os.environ, "GIT_NO_LAZY_FETCH": "1"}, errors="replace").stdout
    res = []
    for rec in out.split("\x01\x02")[1:]:
        head, _, body = rec.partition("\n")
        sha, ct = head.split()
        res.append((sha, int(ct), body))
    return res


def is_revert(body):
    return body.startswith(("Revert ", 'Revert "', "Reland ")) or "\nThis reverts commit " in body


def markers(args):
    rows, samples, near = [], [], []
    for sha, ct, body in git_messages(args.since):
        if is_revert(body):
            continue
        rule = classify(body)
        m = REVIEWED_ON.search(body)
        n = int(m.group(1)) if m else None
        if rule:
            rows.append((sha, n, rule, ct))
            samples.append(matched_line(body))
        else:
            for line in body.splitlines():
                if NEAR.search(line) and not line.lstrip().startswith(">"):
                    near.append(line.strip())
                    break
    path = args.out or os.path.join(store.DATA_DIR, "ai_marked_broad.txt")
    with open(path, "w") as f:
        for sha, n, rule, _ in rows:
            f.write(f"{sha} {n or '-'} {rule}\n")
    print(f"wrote {len(rows):,} marked commits to {path}")
    by = defaultdict(Counter)
    for _, _, rule, ct in rows:
        by[datetime.fromtimestamp(ct, timezone.utc).strftime("%Y-%m")][rule] += 1
    print("month    agent trailer phrase campaign total")
    for mo in sorted(by):
        c = by[mo]
        print(f"{mo}  {c['agent']:>5} {c['trailer']:>7} {c['phrase']:>6} {c['campaign']:>8} {sum(c.values()):>5}")
    if args.sample:
        rnd = random.Random(1)
        print(f"\n== {args.sample} random matches (matched line, cut to 100 chars)")
        for s in rnd.sample(samples, min(args.sample, len(samples))):
            print("  +", s[:100])
        print(f"\n== {args.sample} random near misses")
        for s in rnd.sample(near, min(args.sample, len(near))):
            print("  -", s[:100])


def load_marked(path=None):
    path = path or os.path.join(store.DATA_DIR, "ai_marked_broad.txt")
    out = {}
    for line in open(path):
        sha, n, rule = line.split()
        out[sha] = rule
    return out


