def load(args):
    import balance_analysis as A
    import balance_growth as G
    import balance_report as R
    cls, commits, ids, first, owner_at, _ = G.load_all(args)
    mech = R.mech_set(args.mech)
    dirs3 = A.commit_dirs(3)
    top2, top3 = {}, {}
    for c in commits:
        d = dirs3.get(c["cid"])
        if c["n"] and d:
            top2[c["n"]] = "/".join(d[0].split("/")[:2])
            top3[c["n"]] = d[0]
    A.MECH_FILES = 10 ** 9
    for c in cls:
        if c["change_number"] in mech:
            c["status"] = "MECH"
    use = G.cl_residuals(cls, top2)
    by_n = {c["n"]: c for c in commits if c["n"]}
    broad = load_marked()
    narrow = A.load_ai_marked(args.ai_marked)
    for c in use:
        g = by_n.get(c["change_number"])
        sha = g["sha"] if g else None
        c["sha"] = sha
        c["rule"] = broad.get(sha)
        c["ai"] = c["rule"] is not None
        c["ai_narrow"] = bool(sha and sha in narrow)
        c["d3"] = top3.get(c["change_number"])
        c["q"] = A.quarter(c["closed_at"])
        c["ten"] = (c["closed_at"] - first[c["pid"]]) / G.YEAR if c["pid"] in first else None
        c["ftr"] = (c["first_review_at"] - c["sent_at"]) / 3600 \
            if c["first_review_at"] and c["sent_at"] and c["first_review_at"] >= c["sent_at"] else None
        c["rev30"] = float(bool(c["reverted_at"] and c["reverted_at"] - c["closed_at"] < 30 * DAY))
    return use, commits, first


METRICS = {
    "log lines": lambda c: math.log1p(c["lines"]),
    "threads": lambda c: c["threads"],
    "threads/100 lines": lambda c: 100 * c["threads"] / max(10, c["lines"]),
    "feedback (threads/exp)": lambda c: c["threads"] / c["exp24"] if c["exp24"] else None,
    "interdiff share": lambda c: c["ish"],
    "rounds": lambda c: c["rounds"],
    "h to first review": lambda c: c["ftr"],
    "log h to first review": lambda c: math.log1p(c["ftr"]) if c["ftr"] is not None else None,
    "reverted<30d": lambda c: c["rev30"],
}


def concentration(use):
    """How many authors each rule's marked CLs come from, and the share from
    the five busiest (aggregate only, no names)."""
    print("\n== Who the marked CLs come from (merged human-owned CLs since mid-2023, mechanical excluded)")
    print(f"{'rule':10} {'CLs':>6} {'authors':>8} {'top-5 share':>12} {'top-1 share':>12}")
    for rule in ("agent", "trailer", "phrase", "campaign", None):
        cs = [c for c in use if (c["rule"] == rule if rule else c["ai"])]
        if not cs:
            continue
        per = sorted(Counter(c["pid"] for c in cs).values(), reverse=True)
        print(f"{rule or 'all':10} {len(cs):>6} {len(per):>8} {sum(per[:5]) / len(cs):>12.0%} {per[0] / len(cs):>12.0%}")


def ci(ds):
    m = st.mean(ds)
    se = st.stdev(ds) / math.sqrt(len(ds)) if len(ds) > 1 else float("nan")
    return m, m - 1.96 * se, m + 1.96 * se


def paired(use, flag="ai", label="broad"):
    grp = defaultdict(lambda: ([], []))
    for c in use:
        grp[(c["pid"], c["q"])][0 if c[flag] else 1].append(c)
    pairs = [(a, b) for a, b in grp.values() if a and b]
    print(f"\n== Same author, same quarter ({label} marker): {len(pairs)} author-quarters, "
          f"{sum(len(a) for a, _ in pairs):,} marked CLs")
    print(f"{'measure':22} {'marked-unmarked':>16} {'95% CI':>22} {'n':>6}")
    for name, f in METRICS.items():
        ds = []
        for a, b in pairs:
            va = [f(c) for c in a if f(c) is not None]
            vb = [f(c) for c in b if f(c) is not None]
            if va and vb:
                ds.append(st.mean(va) - st.mean(vb))
        if len(ds) >= 10:
            m, lo, hi = ci(ds)
            print(f"{name:22} {m:>+16.3f} {lo:>+10.3f} .. {hi:>+8.3f} {len(ds):>6}")


def event_person(use):
    """Each author's UNMARKED CLs by quarter relative to their first marked CL,
    minus the same calendar quarter's mean for never-marked authors with
    similar tenure (a matched control): does starting to use AI change all of
    someone's work, not just the marked CLs?"""
    import balance_analysis as A
    first_mark = {}
    for c in sorted(use, key=lambda c: c["closed_at"]):
        if c["ai"] and c["pid"] not in first_mark:
            first_mark[c["pid"]] = c["q"]
    qs = sorted({c["q"] for c in use})
    qi = {q: i for i, q in enumerate(qs)}
    band = lambda t: "na" if t is None else "<1" if t < 1 else "1-3" if t < 3 else "3-8" if t < 8 else "8+"
    ctrl = defaultdict(lambda: defaultdict(list))
    for c in use:
        if c["pid"] not in first_mark:
            ctrl[(c["q"], band(c["ten"]))]["all"].append(c)
    print(f"\n== Event study by person: {len(first_mark):,} authors with a marked CL; their UNMARKED CLs, "
          "relative quarter to the first mark, minus never-marked authors of the same tenure band that quarter")
    names = ["log lines", "threads/100 lines", "feedback (threads/exp)", "interdiff share", "log h to first review",
             "reverted<30d"]
    print(f"{'rel q':>5} {'people':>7} " + " ".join(f"{n[:14]:>15}" for n in names))
    cache = {}

    def cmean(key, name):
        k = (key, name)
        if k not in cache:
            v = [METRICS[name](c) for c in ctrl[key]["all"]]
            v = [x for x in v if x is not None]
            cache[k] = st.mean(v) if v else None
        return cache[k]
    # Per person first (their mean gap that relative quarter), then across
    # people, so the ± is over authors, not over correlated CLs.
    per = defaultdict(lambda: defaultdict(lambda: defaultdict(list)))
    for c in use:
        fm = first_mark.get(c["pid"])
        if not fm or c["ai"]:
            continue
        rel = qi[c["q"]] - qi[fm]
        if -4 <= rel <= 4:
            for n in names:
                v = METRICS[n](c)
                base = cmean((c["q"], band(c["ten"])), n)
                if v is not None and base is not None:
                    per[rel][n][c["pid"]].append(v - base)
    rows = {rel: {n: [st.mean(v) for v in byp.values()] for n, byp in d.items()} for rel, d in per.items()}
    for rel in range(-4, 5):
        r = rows.get(rel)
        if not r:
            continue
        cells = []
        for n in names:
            v = r.get(n, [])
            if len(v) >= 10:
                m, lo, hi = ci(v)
                cells.append(f"{m:+.3f}±{(hi - lo) / 2:.3f}".rjust(15))
            else:
                cells.append(f"{'':>15}")
        print(f"{rel:>+5} {len(r[names[0]]):>7} " + " ".join(cells))


