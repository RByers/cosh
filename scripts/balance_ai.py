FOOTERS = {
    "Owners-Override": re.compile(r"^Owners-Override:", re.M),
    "Auto-Submit": re.compile(r"^Auto-Submit:", re.M),
    "Low-Coverage-Reason": re.compile(r"^Low-Coverage-Reason:", re.M),
    "No-Try": re.compile(r"^No-Try:\s*true", re.M | re.I),
    "No-Presubmit": re.compile(r"^No-Presubmit:\s*true", re.M | re.I),
    "No-Tree-Checks": re.compile(r"^No-Tree-Checks:\s*true", re.M | re.I),
    "Disable-Rts": re.compile(r"^Disable-Rts:", re.M),
    "Validate-Test-Flakiness": re.compile(r"^Validate-Test-Flakiness:", re.M),
    "Include-Ci-Only-Tests": re.compile(r"^Include-Ci-Only-Tests:", re.M),
    "Commit-Queue": re.compile(r"^Cq-Include-Trybots:", re.M),
    "Bug": re.compile(r"^(?:Bug|Fixed):", re.M),
}


def footer_counts(since="2017-01-01"):
    """{sha: frozenset of footer names} for main's first-parent history since
    `since`, streamed line by line (the messages run to gigabytes)."""
    p = subprocess.Popen(["git", "-C", SHARED, "log", "--first-parent", f"--since={since}", "main",
                          "--format=%x01%x02%H"  + "%n%B"], stdout=subprocess.PIPE, text=True, errors="replace",
                         env={**os.environ, "GIT_NO_LAZY_FETCH": "1"})
    res, sha, cur = {}, None, set()
    keys = list(FOOTERS.items())
    for line in p.stdout:
        if line.startswith("\x01\x02"):
            if sha:
                res[sha] = frozenset(cur)
            sha, cur = line[2:].strip(), set()
            continue
        if ":" in line[:40]:
            for k, rx in keys:
                if k not in cur and rx.match(line):
                    cur.add(k)
    if sha:
        res[sha] = frozenset(cur)
    if p.wait():
        raise RuntimeError("git log failed")
    return res


def footers(use, commits):
    import balance_analysis as A
    fs = footer_counts()
    by_q = defaultdict(Counter)
    tot = Counter()
    for c in commits:
        if not c["n"] or c["is_revert"]:
            continue
        q = A.quarter(c["at"])
        tot[q] += 1
        for k in fs.get(c["sha"], ()):
            by_q[q][k] += 1
    names = [k for k in FOOTERS if k != "Commit-Queue"]
    print("\n== Share of human commits with each footer, by year (Q3 of each year, then 2026 quarters)")
    print(f"{'q':7} {'commits':>8} " + " ".join(f"{k[:12]:>12}" for k in names))
    for q in sorted(tot):
        if q.endswith("Q3") or q >= "2025Q4":
            print(f"{q:7} {tot[q]:>8} " + " ".join(f"{by_q[q][k] / tot[q]:>12.2%}" for k in names))
    # Relation to review, Gerrit era: CLs with vs without each footer, same author-quarter.
    for c in use:
        c["foot"] = fs.get(c["sha"], set()) if c["sha"] else set()
    print("\n== Gerrit era: CLs with each footer minus the same author's other CLs that quarter (paired)")
    for k in ("Owners-Override", "Auto-Submit", "Low-Coverage-Reason", "No-Try", "Disable-Rts",
              "Validate-Test-Flakiness"):
        grp = defaultdict(lambda: ([], []))
        for c in use:
            grp[(c["pid"], c["q"])][0 if k in c["foot"] else 1].append(c)
        pairs = [(a, b) for a, b in grp.values() if a and b]
        n_cls = sum(len(a) for a, _ in pairs)
        out = []
        for name in ("log lines", "feedback (threads/exp)", "h to first review", "reverted<30d"):
            f = METRICS[name]
            ds = []
            for a, b in pairs:
                va = [f(c) for c in a if f(c) is not None]
                vb = [f(c) for c in b if f(c) is not None]
                if va and vb:
                    ds.append(st.mean(va) - st.mean(vb))
            if len(ds) >= 10:
                m, lo, hi = ci(ds)
                out.append(f"{name} {m:+.3f} [{lo:+.3f},{hi:+.3f}]")
        print(f"  {k:24} {len(pairs):>5} author-quarters, {n_cls:>6} CLs: " + "; ".join(out))
    # Owners-Override against reviewer scarcity: dir2 x half-year correlation with
    # approvals per approver (busy approvers) and the override rate.
    print("\n== Owners-Override rate vs approvals per active approver, by 2-level directory and year (2019..2026)")
    import balance_growth as G  # noqa: F401
    dirs3 = A.commit_dirs(3)
    cell = defaultdict(lambda: [0, 0, Counter()])
    for c in commits:
        if not c["n"] or c["is_revert"]:
            continue
        d = dirs3.get(c["cid"])
        if not d:
            continue
        y = A.year(c["at"])
        if y < 2019:
            continue
        key = ("/".join(d[0].split("/")[:2]), y)
        x = cell[key]
        x[0] += 1
        x[1] += "Owners-Override" in fs.get(c["sha"], ())
        for r in c["rbp"]:
            if r != c["pid"]:
                x[2][r] += 1
    pts = [(v[1] / v[0], v[0] / max(1, len(v[2]))) for v in cell.values() if v[0] >= 200 and v[2]]
    if len(pts) > 10:
        xs, ys = zip(*pts)
        r = st.correlation(xs, ys)
        print(f"  {len(pts)} dir-years with >= 200 commits: Pearson r(override rate, commits per approver) = {r:+.2f}")
    by_y = defaultdict(lambda: [0, 0])
    for (d, y), v in cell.items():
        by_y[y][0] += v[0]
        by_y[y][1] += v[1]
    print("  year  override rate")
    for y in sorted(by_y):
        print(f"  {y}  {by_y[y][1] / by_y[y][0]:.2%}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("what", choices=["markers", "paired", "did", "footers"])
    ap.add_argument("--since", default="2024-01-01")
    ap.add_argument("--sample", type=int, default=0)
    ap.add_argument("--out")
    ap.add_argument("--first-commit", help="default: commits.sqlite")
    ap.add_argument("--owners-added", help="default: commits.sqlite")
    ap.add_argument("--ai-marked", help="the narrow (Agent-Generated) list, for comparison (default: commits.sqlite)")
    ap.add_argument("--mech", help="default: commits.sqlite")
    args = ap.parse_args()
    if args.what == "markers":
        markers(args)
        return
    use, commits, first = load(args)
    if args.what == "paired":
        concentration(use)
        paired(use, "ai_narrow", "narrow: earlier list")
        paired(use, "ai", "broad")
        for rule in ("agent", "trailer", "phrase", "campaign"):
            for c in use:
                c["ai_rule"] = c["rule"] == rule
            paired(use, "ai_rule", f"broad, rule {rule} only")
        for c in use:
            c["ai_nc"] = c["ai"] and c["rule"] != "campaign"
        paired(use, "ai_nc", "broad without the campaign")
        event_person(use)
    elif args.what == "did":
        did(use)
    elif args.what == "footers":
        footers(use, commits)


if __name__ == "__main__":
    main()
