"""Derive cosh.sqlite (accounts, changes, reviews) from cached raw responses.
Pure function of raw.sqlite: safe to re-run any time; never hits the network."""

import json
import os
import sys
import zlib

from . import store
from .bots import is_bot_account
from .extract import closed_ts, iso_week_of, parse_gerrit_ts

METRIC_VERSION = "1"


def human_text(message):
    """Comment text minus quoted reply lines ('> ...')."""
    lines = [l for l in (message or "").splitlines() if not l.lstrip().startswith(">")]
    return "\n".join(lines).strip()


DELETED_USER = "Deleted User"   # what Gerrit's UI shows for a deleted account

# Upsert for accounts.name: a real name wins over the Deleted User placeholder.
NAME_UPSERT = (f"name = CASE WHEN excluded.name IS NULL OR excluded.name = '{DELETED_USER}' "
               f"THEN coalesce(name, excluded.name) ELSE excluded.name END")


def account_name(a):
    """Full name, or Gerrit's display_name when there is none (some service and
    AI-agent accounts have only a display_name), or "Deleted User" for a
    deleted account with neither, matching Gerrit's UI."""
    return a.get("name") or a.get("display_name") or (DELETED_USER if a.get("deleted") else None)


def mark_emailless_bots(db):
    """Treat every account that still has no email as a bot or AI agent.
    Run after all accounts are loaded: a later sighting may supply the email."""
    return db.execute("UPDATE accounts SET is_bot = 1 WHERE email IS NULL AND is_bot = 0").rowcount


def is_ai_comment(c):
    return bool(c.get("is_ai")) or (c.get("tag") or "").startswith("autogenerated:")


def derive_change(change, comments):
    """Return (accounts{id: acct}, change_row_dict, {account_id: review_dict}).

    comments: parsed /comments map (path -> [comment]) or None if not fetched.
    """
    accounts = {}

    def see(a):
        if a and a.get("_account_id") is not None:
            cur = accounts.get(a["_account_id"])
            if cur is None or (not cur.get("email") and a.get("email")) or \
                    (not cur.get("tags") and a.get("tags")):
                accounts[a["_account_id"]] = {**(cur or {}), **a}

    # Account details (email, SERVICE_USER tag) can appear anywhere in the
    # listing JSON: owner, reviewers, labels, attention set, submitter...
    stack = [change]
    while stack:
        o = stack.pop()
        if isinstance(o, dict):
            if isinstance(o.get("_account_id"), int):
                see(o)
            stack.extend(v for v in o.values() if isinstance(v, (dict, list)))
        elif isinstance(o, list):
            stack.extend(o)

    owner = change["owner"]
    owner_id = owner["_account_id"]
    closed = parse_gerrit_ts(closed_ts(change))

    reviews = {}

    def row(aid):
        return reviews.setdefault(aid, dict(review_comments=0, review_chars=0,
                                            ai_comments=0, post_merge_comments=0,
                                            voted_cr=None))

    if is_bot_account(owner):
        # Bot commit (autoroll etc.): keep the change row, no review rows.
        comments = None
        labels = []
    else:
        labels = change.get("labels", {}).get("Code-Review", {}).get("all", []) or []
    for v in labels:
        see(v)
        aid = v.get("_account_id")
        if aid is None or aid == owner_id or not v.get("value"):
            continue
        row(aid)["voted_cr"] = v["value"]

    for clist in (comments or {}).values():
        for c in clist:
            a = c.get("author") or {}
            see(a)
            aid = a.get("_account_id")
            if aid is None or aid == owner_id:
                continue
            r = row(aid)
            if is_ai_comment(c):
                r["ai_comments"] += 1
            elif c.get("updated") and parse_gerrit_ts(c["updated"]) > closed:
                r["post_merge_comments"] += 1
            else:
                r["review_comments"] += 1
                r["review_chars"] += len(human_text(c.get("message")))

    ch = dict(
        change_number=change["_number"], project=change["project"],
        branch=change["branch"], change_id=change.get("change_id"),
        owner_account=owner_id, status=change["status"], created_at=change["created"][:19],
        submitted_at=(change.get("submitted") or "")[:19] or None,
        closed_at=closed_ts(change)[:19], iso_week=iso_week_of(closed_ts(change)),
        insertions=change.get("insertions"), deletions=change.get("deletions"),
        patchsets=change.get("current_revision_number"),
        total_comment_count=change.get("total_comment_count"),
        is_bot_owned=int(is_bot_account(owner)), subject=change.get("subject"))
    return accounts, ch, reviews


def load_comments(raw, repos, host, project, number, source):
    """Comments for a CL from NoteDb (preferred) or the REST cache.
    source: 'auto' | 'notedb' | 'rest'. Returns (comments_or_None, source_used)."""
    from . import notedb
    if source in ("auto", "notedb"):
        if project not in repos:
            path = notedb.default_repo(project)
            repos[project] = (path, notedb.fetched_numbers(path)) if os.path.isdir(path) else (None, set())
        path, have = repos[project]
        if number in have:
            return notedb.read_comments(path, number), "notedb"
    if source in ("auto", "rest"):
        cm = store.get_response(raw, host, "comments", str(number))
        if cm and cm[0] == 200:
            return json.loads(cm[1]), "rest"
    return None, None


def derive(data_dir=store.DATA_DIR, weeks=None, source="auto"):
    raw = store.open_raw(data_dir)
    db = store.open_cosh(data_dir)
    with db:   # accounts resolved via /accounts/{id} (ids seen only in NoteDb)
        for host, body in raw.execute(
                "SELECT host, body_zlib FROM responses WHERE kind='account' AND http_status=200"):
            a = json.loads(zlib.decompress(body))
            db.execute("""INSERT INTO accounts VALUES (?,?,?,?,?) ON CONFLICT(host, account_id)
                          DO UPDATE SET email=coalesce(excluded.email, email),
                          """ + NAME_UPSERT,
                       (host, a["_account_id"], a.get("email"), account_name(a),
                        int(is_bot_account(a))))
    repos = {}
    sources = {}
    q = "SELECT host, project, iso_week, change_number, window_key FROM week_changes"
    rows = raw.execute(q).fetchall()
    if weeks:
        rows = [r for r in rows if r[2] in weeks]

    window_cache = {}
    n_changes = n_reviews = 0
    for host, project, iso_week, number, wkey in rows:
        if (host, wkey) not in window_cache:
            _, body = store.get_response(raw, host, "list_window", wkey)
            window_cache[(host, wkey)] = {c["_number"]: c for c in json.loads(body)}
        change = window_cache[(host, wkey)][number]
        comments, used = load_comments(raw, repos, host, project, number, source)
        sources[used] = sources.get(used, 0) + 1

        accounts, ch, reviews = derive_change(change, comments)
        with db:
            for aid, a in accounts.items():
                db.execute(
                    """INSERT INTO accounts VALUES (?,?,?,?,?) ON CONFLICT(host, account_id)
                       DO UPDATE SET email=coalesce(excluded.email, email),
                       is_bot=max(is_bot, excluded.is_bot), """ + NAME_UPSERT,
                    (host, aid, a.get("email"), account_name(a), int(is_bot_account(a))))
            cols = list(ch)
            db.execute(
                f"INSERT OR REPLACE INTO changes(host,{','.join(cols)}) "
                f"VALUES (?,{','.join('?' * len(cols))})", [host] + [ch[c] for c in cols])
            db.execute("DELETE FROM reviews WHERE host=? AND change_number=?", (host, number))
            db.executemany(
                """INSERT INTO reviews(host, change_number, account_id, review_comments,
                   review_chars, ai_comments, post_merge_comments, voted_cr)
                   VALUES (?,?,?,?,?,?,?,?)""",
                [(host, number, aid, r["review_comments"], r["review_chars"],
                  r["ai_comments"], r["post_merge_comments"], r["voted_cr"])
                 for aid, r in reviews.items()])
        n_changes += 1
        n_reviews += len(reviews)
    with db:
        n_emailless = mark_emailless_bots(db)
        db.execute("INSERT OR REPLACE INTO meta VALUES ('metric_version', ?)", (METRIC_VERSION,))
        db.execute("INSERT OR REPLACE INTO meta VALUES ('derived_at', ?)", (store.now_iso(),))
    print(f"derived {n_changes} changes, {n_reviews} review rows; "
          f"comment source per CL: {sources}; {n_emailless} accounts without email marked as bots",
          file=sys.stderr)
    raw.close()
    db.close()
