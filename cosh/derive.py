"""Derive derived.sqlite (accounts, committers, changes, comments) from cached raw
responses and NoteDb. Each comment is keyed by the week it was written and
keeps its file path; each CL records its anchor file (cosh/paths.py). Since
metric_version 6 summarize places patchset-level comments on each reviewer's
own anchor instead, so changes.anchor_path is informational.

Pure function of raw.sqlite + NoteDb, which it opens read-only: safe to re-run
any time, even while an extractor is running; never hits the network."""

import hashlib
import json
import os
import sys
import zlib
from collections import defaultdict
from . import store
from .bots import is_bot_account
from .extract import closed_ts, iso_week_of, parse_gerrit_ts
from .classify import build_threads, thread_row
from .paths import anchor, is_file

# 1-2 = CL-keyed (cosh.sqlite); 3 = activity-time keyed; 4 = AI comments in the
# headline (summarize only); 5 = comments only (no vote-only reviews), each
# placed on a file and filtered by config/paths.txt; 6 = a patchset-level comment
# is placed on its author's own most-commented file on the CL, else unplaced,
# and accounts that never commented inline are dropped (summarize only); 7 =
# threads (root_uuid, threads table) and the addressed_comments metric.
METRIC_VERSION = "7"


def _branch(name):
    """chromium/src's `master` was renamed `main` in April 2021: one branch."""
    return "main" if name == "master" else name

def human_text(message):
    """Comment text minus quoted reply lines ('> ...')."""
    lines = [l for l in (message or "").splitlines() if not l.lstrip().startswith(">")]
    return "\n".join(lines).strip()


DELETED_USER = "Deleted User"   # what Gerrit's UI shows for a deleted account

# Upsert for accounts.name: a real name wins over the Deleted User placeholder.
NAME_UPSERT = (f"name = CASE WHEN excluded.name IS NULL OR excluded.name = '{DELETED_USER}' "
               f"THEN coalesce(name, excluded.name) ELSE excluded.name END")
ACCOUNT_UPSERT = ("""INSERT INTO accounts VALUES (?,?,?,?,?) ON CONFLICT(host, account_id)
                     DO UPDATE SET email=coalesce(excluded.email, email),
                     is_bot=max(is_bot, excluded.is_bot), """ + NAME_UPSERT)


def account_name(a):
    """Full name, or Gerrit's display_name when there is none (some service and
    AI-agent accounts have only a display_name), or "Deleted User" for a
    deleted account with neither, matching Gerrit's UI."""
    return a.get("name") or a.get("display_name") or (DELETED_USER if a.get("deleted") else None)


def mark_emailless_bots(db):
    """Treat every account that still has no email as a bot or AI agent.
    Run after all accounts are loaded: a later sighting may supply the email."""
    return db.execute("UPDATE accounts SET is_bot = 1 WHERE email IS NULL AND is_bot = 0").rowcount


# Newest listing wins; within one listing time, "may vote" wins.
COMMITTER_UPSERT = """INSERT INTO committers VALUES (?,?,?,?) ON CONFLICT(host, account_id)
    DO UPDATE SET is_committer = CASE WHEN excluded.seen_at > seen_at THEN excluded.is_committer
                                      WHEN excluded.seen_at = seen_at THEN max(is_committer, excluded.is_committer)
                                      ELSE is_committer END,
                  seen_at = max(seen_at, excluded.seen_at)"""


def committer_evidence(change):
    """{account id: 1 or 0}: whether each account listed on the CL's
    Code-Review label may vote it (only committers may; docs/committers.md).
    A permitted range means yes. No range means no only on an open or
    abandoned CL: on a merged one Gerrit clips the range to the vote already
    cast, so a committer who didn't vote shows none either."""
    out = {}
    can_say_no = change.get("status") in ("NEW", "ABANDONED")
    for a in ((change.get("labels") or {}).get("Code-Review") or {}).get("all") or []:
        aid = a.get("_account_id")
        if aid is None:
            continue
        if a.get("permitted_voting_range"):
            out[aid] = 1
        elif can_say_no:
            out.setdefault(aid, 0)
    return out


def is_ai_comment(c):
    return bool(c.get("is_ai")) or (c.get("tag") or "").startswith("autogenerated:")


def close_time(change):
    """Closing timestamp (Gerrit format) or None for an open CL."""
    if change.get("status") not in ("MERGED", "ABANDONED"):
        return None
    return closed_ts(change)


def _ts(gerrit_ts):
    return gerrit_ts[:19]


def derive_change(change, comments):
    """Return (accounts{id: acct}, change_row, [comment_row]).

    comments: parsed /comments map (path -> [comment]) or None if not fetched.
    Rows cover non-owner comments on human-owned CLs only; a bot-owned CL
    (autoroll etc.) gets its change row and nothing else. The change row's
    anchor_path counts every author's inline comments, the owner's included.
    """
    accounts = {}

    def see(a):
        if a and a.get("_account_id") is not None:
            cur = accounts.get(a["_account_id"])
            if cur is None or (not cur.get("email") and a.get("email")) or \
                    (not cur.get("tags") and a.get("tags")):
                accounts[a["_account_id"]] = {**(cur or {}), **a}

    # Account details (email, SERVICE_USER tag) can appear anywhere in the
    # listing JSON: owner, reviewers, labels, attention set, submitter...
    stack = [change]
    while stack:
        o = stack.pop()
        if isinstance(o, dict):
            if isinstance(o.get("_account_id"), int):
                see(o)
            stack.extend(v for v in o.values() if isinstance(v, (dict, list)))
        elif isinstance(o, list):
            stack.extend(o)

    owner = change["owner"]
    owner_id = owner["_account_id"]
    bot_owned = is_bot_account(owner)
    closed = close_time(change)
    closed_dt = parse_gerrit_ts(closed) if closed else None

    rows = []
    root_of = {} if bot_owned else {cid: t["root_id"] for t in build_threads(comments, owner_id, True)
                                    for cid, *_ in t["items"]}
    for path, clist in ({} if bot_owned else (comments or {})).items():
        for c in clist:
            a = c.get("author") or {}
            see(a)
            aid = a.get("_account_id")
            if aid is None or aid == owner_id or not c.get("updated"):
                continue
            cid = c.get("id") or hashlib.sha1(
                f"{path}|{aid}|{c['updated']}|{c.get('message')}".encode()).hexdigest()
            rows.append(dict(
                comment_id=cid, account_id=aid, written_at=_ts(c["updated"]),
                iso_week=iso_week_of(c["updated"]),
                path=path, chars=len(human_text(c.get("message"))), is_ai=int(is_ai_comment(c)),
                after_close=int(closed_dt is not None and parse_gerrit_ts(c["updated"]) > closed_dt),
                root_uuid=root_of.get(cid)))

    ch = dict(
        change_number=change["_number"], project=change["project"],
        branch=_branch(change["branch"]), change_id=change.get("change_id"),
        owner_account=owner_id, status=change["status"], created_at=_ts(change["created"]),
        updated_at=_ts(change["updated"]),
        submitted_at=_ts(change.get("submitted") or "") or None,
        closed_at=_ts(closed) if closed else None,
        close_week=iso_week_of(closed) if closed else None,
        insertions=change.get("insertions"), deletions=change.get("deletions"),
        patchsets=change.get("current_revision_number"),
        total_comment_count=change.get("total_comment_count"),
        is_bot_owned=int(bot_owned), subject=change.get("subject"),
        anchor_path=None if bot_owned else anchor(
            {p: len(cs) for p, cs in (comments or {}).items() if is_file(p)}))
    return accounts, ch, rows


def derive_threads(change, comments):
    """threads rows (cosh/classify.py, thread_row) for a human-owned CL."""
    if is_bot_account(change["owner"]):
        return []
    owner_id = change["owner"]["_account_id"]
    return [thread_row(t, owner_id) for t in build_threads(comments, owner_id)]


def notedb_repo(repos, project):
    """(repo path, set of change numbers fetched) for a project, cached in `repos`."""
    from . import notedb
    if project not in repos:
        path = notedb.default_repo(project)
        repos[project] = (path, notedb.fetched_numbers(path)) if os.path.isdir(path) else (None, set())
    return repos[project]


def prefetch_notedb(repos, cls, source):
    """{change number: comments} from NoteDb for the CLs in `cls` ((host,
    project, number) tuples), read in one batch per project."""
    from . import notedb
    if source not in ("auto", "notedb"):
        return {}
    by_project = defaultdict(list)
    for _, project, number in cls:
        if number in notedb_repo(repos, project)[1]:
            by_project[project].append(number)
    out = {}
    for project, numbers in by_project.items():
        out.update(notedb.read_comments_many(repos[project][0], numbers))
    return out


def load_comments(raw, repos, host, project, number, source, prefetched=None):
    """Comments for a CL from NoteDb (preferred) or the REST cache.
    source: 'auto' | 'notedb' | 'rest'. prefetched: prefetch_notedb's result
    for a batch holding this CL. Returns (comments_or_None, source_used)."""
    from . import notedb
    if source in ("auto", "notedb"):
        if prefetched is not None and number in prefetched:
            return prefetched[number], "notedb"
        path, have = notedb_repo(repos, project)
        if prefetched is None and number in have:
            comments = notedb.read_comments(path, number)
            if comments is not None:
                return comments, "notedb"
    if source in ("auto", "rest"):
        cm = store.get_response(raw, host, "comments", str(number))
        if cm and cm[0] == 200:
            return json.loads(cm[1]), "rest"
    return None, None


def listing_index(raw):
    """{(host, project, change_number): [window_key, ...]}: every listing of
    every CL, from the weekly (closed-CL) index and any open-CL snapshots."""
    idx = defaultdict(list)
    for h, p, n, k in raw.execute(
            "SELECT host, project, change_number, window_key FROM week_changes"):
        idx[(h, p, n)].append(k)
    if store.has_table(raw, "open_changes"):
        for h, p, n, k in raw.execute(
                "SELECT host, project, change_number, window_key FROM open_changes"):
            idx[(h, p, n)].append(k)
    return idx


def _window(raw, host, key):
    _, body = store.get_response(raw, host, "list_window", key)
    return {c["_number"]: c for c in json.loads(body)}


def choose_listings(raw, idx, wanted):
    """{cl: window_key of its newest listing (largest `updated`)} for CLs in
    `wanted`. Only CLs listed more than once need their windows read here."""
    best = {}
    multi = defaultdict(list)          # (host, window_key) -> [cl]
    for cl in wanted:
        keys = sorted(set(idx[cl]))
        if len(keys) == 1:
            best[cl] = keys[0]
        else:
            for k in keys:
                multi[(cl[0], k)].append(cl)
    newest = {}
    for (host, k), cls in sorted(multi.items()):
        win = _window(raw, host, k)
        for cl in cls:
            u = win[cl[2]]["updated"]
            if cl not in newest or u > newest[cl][0]:
                newest[cl] = (u, k)
    best.update({cl: k for cl, (_, k) in newest.items()})
    return best


def derive(data_dir=store.DATA_DIR, weeks=None, source="auto", out_path=None):
    """Rebuild rows for every CL (default), or only for CLs in the given
    weekly listings (`weeks`, used by backfill after each week)."""
    raw = store.open_raw_ro(data_dir)
    db = store.open_derived(data_dir, out_path)
    with db:   # accounts resolved via /accounts/{id} (ids seen only in NoteDb)
        for host, body in raw.execute(
                "SELECT host, body_zlib FROM responses WHERE kind='account' AND http_status=200"):
            a = json.loads(zlib.decompress(body))
            db.execute(ACCOUNT_UPSERT, (host, a["_account_id"], a.get("email"),
                                        account_name(a), int(is_bot_account(a))))
    # Read which weeks are complete *before* reading the CL index: a backfill
    # may finish more weeks while this runs, and claiming a week whose CLs
    # weren't derived would make summaries report it as complete but empty.
    fetched_weeks = sorted(w for (w,) in raw.execute(
        "SELECT DISTINCT iso_week FROM week_progress WHERE fetched_at IS NOT NULL"))
    snapshot = None
    if store.has_table(raw, "open_listings"):
        snapshot = raw.execute("SELECT max(listed_at) FROM open_listings "
                               "WHERE fetched_at IS NOT NULL").fetchone()[0]
    idx = listing_index(raw)
    if weeks:
        wanted = {(h, p, n) for h, p, w, n in raw.execute(
            "SELECT host, project, iso_week, change_number FROM week_changes")
            if w in weeks}
    else:
        wanted = set(idx)
    best = choose_listings(raw, idx, wanted)
    by_window = defaultdict(list)
    for cl, k in best.items():
        by_window[(cl[0], k)].append(cl)

    repos, sources = {}, defaultdict(int)
    n_changes = n_comments = 0
    for (host, k), cls in sorted(by_window.items()):
        win = _window(raw, host, k)    # one window in memory at a time
        listed_at = raw.execute("SELECT fetched_at FROM responses WHERE host=? AND "
                                "kind='list_window' AND key=?", (host, k)).fetchone()[0]
        notes = prefetch_notedb(repos, cls, source)
        with db:
            for _, project, number in cls:
                change = win[number]
                comments, used = load_comments(raw, repos, host, project, number, source, notes)
                sources[used] += 1
                accounts, ch, rows = derive_change(change, comments)
                for aid, a in accounts.items():
                    db.execute(ACCOUNT_UPSERT, (host, aid, a.get("email"), account_name(a),
                                                int(is_bot_account(a))))
                db.executemany(COMMITTER_UPSERT, [(host, aid, v, listed_at)
                                                  for aid, v in committer_evidence(change).items()])
                cols = list(ch)
                db.execute(f"INSERT OR REPLACE INTO changes(host,{','.join(cols)}) "
                           f"VALUES (?,{','.join('?' * len(cols))})", [host] + [ch[c] for c in cols])
                db.execute("DELETE FROM comments WHERE host=? AND change_number=?", (host, number))
                db.executemany(
                    """INSERT INTO comments(host, change_number, comment_id, account_id, written_at,
                       iso_week, path, chars, is_ai, after_close, root_uuid)
                       VALUES (?,?,?,?,?,?,?,?,?,?,?) ON CONFLICT DO NOTHING""",
                    [(host, number, r["comment_id"], r["account_id"], r["written_at"], r["iso_week"],
                      r["path"], r["chars"], r["is_ai"], r["after_close"], r["root_uuid"]) for r in rows])
                db.execute("DELETE FROM threads WHERE host=? AND change_number=?", (host, number))
                db.executemany(
                    """INSERT INTO threads(host, change_number, root_uuid, root_account, n_comments,
                       last_owner_reply_at, input_hash, regex_addressed) VALUES (?,?,?,?,?,?,?,?)
                       ON CONFLICT DO NOTHING""",
                    [(host, number, t["root_uuid"], t["root_account"], t["n_comments"],
                      t["last_owner_reply_at"], t["input_hash"], t["regex_addressed"])
                     for t in derive_threads(change, comments)])
                n_changes += 1
                n_comments += len(rows)

    with db:
        n_emailless = mark_emailless_bots(db)
        for k, v in [("metric_version", METRIC_VERSION), ("derived_at", store.now_iso()),
                     ("fetched_weeks", json.dumps(fetched_weeks)), ("open_snapshot_at", snapshot)]:
            db.execute("INSERT OR REPLACE INTO meta VALUES (?, ?)", (k, v))
    print(f"derived {n_changes} changes, {n_comments} comments; "
          f"comment source per CL: {dict(sources)}; {n_emailless} accounts without email "
          f"marked as bots", file=sys.stderr)
    raw.close()
    db.close()
