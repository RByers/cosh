"""SQLite storage: raw.sqlite (response cache + progress, source of truth) and
cosh.sqlite (derived tables, rebuildable). See docs/storage-design.md §3."""

import hashlib
import os
import sqlite3
import zlib
from datetime import datetime, timezone

DATA_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "data", "private")

RAW_SCHEMA = """
CREATE TABLE IF NOT EXISTS responses (
  host        TEXT    NOT NULL,
  kind        TEXT    NOT NULL,      -- 'list_window' | 'comments' (REST) | 'account'
  key         TEXT    NOT NULL,      -- window spec, or change number
  url         TEXT    NOT NULL,
  fetched_at  TEXT    NOT NULL,
  http_status INTEGER NOT NULL,
  body_zlib   BLOB    NOT NULL,      -- zlib(body without XSSI prefix)
  body_sha256 TEXT    NOT NULL,
  PRIMARY KEY (host, kind, key)
) STRICT, WITHOUT ROWID;

CREATE TABLE IF NOT EXISTS extract_runs (
  run_id      INTEGER PRIMARY KEY,
  started_at  TEXT NOT NULL,
  finished_at TEXT,
  command     TEXT NOT NULL,
  requests    INTEGER,
  status      TEXT NOT NULL          -- running | ok | failed | interrupted
) STRICT;

CREATE TABLE IF NOT EXISTS week_progress (
  host          TEXT NOT NULL,
  project       TEXT NOT NULL,
  iso_week      TEXT NOT NULL,
  listed_at     TEXT,
  cl_count      INTEGER,
  fetched_at    TEXT,                -- all comment fetches done
  last_run_id   INTEGER,
  PRIMARY KEY (host, project, iso_week)
) STRICT;

CREATE TABLE IF NOT EXISTS week_changes (
  host TEXT NOT NULL, project TEXT NOT NULL, iso_week TEXT NOT NULL,
  change_number INTEGER NOT NULL,
  window_key    TEXT NOT NULL,       -- which list_window response holds its JSON
  PRIMARY KEY (host, project, iso_week, change_number)
) STRICT, WITHOUT ROWID;
"""

COSH_SCHEMA = """
CREATE TABLE IF NOT EXISTS meta (k TEXT PRIMARY KEY, v TEXT) STRICT;

CREATE TABLE IF NOT EXISTS accounts (
  host        TEXT    NOT NULL,
  account_id  INTEGER NOT NULL,
  email       TEXT,
  name        TEXT,
  is_bot      INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (host, account_id)
) STRICT;
CREATE INDEX IF NOT EXISTS accounts_email ON accounts(email);

CREATE TABLE IF NOT EXISTS changes (
  host                TEXT    NOT NULL,
  change_number       INTEGER NOT NULL,
  project             TEXT    NOT NULL,
  branch              TEXT    NOT NULL,
  change_id           TEXT,
  owner_account       INTEGER NOT NULL,
  status              TEXT    NOT NULL,   -- MERGED | ABANDONED
  created_at          TEXT    NOT NULL,
  submitted_at        TEXT,               -- NULL for abandoned
  closed_at           TEXT    NOT NULL,   -- submit time, or `updated` for abandoned
  iso_week            TEXT    NOT NULL,   -- ISO week of closed_at
  insertions          INTEGER,
  deletions           INTEGER,
  patchsets           INTEGER,
  total_comment_count INTEGER,
  is_bot_owned        INTEGER NOT NULL DEFAULT 0,
  subject             TEXT,
  PRIMARY KEY (host, change_number)
) STRICT;
CREATE INDEX IF NOT EXISTS changes_week ON changes(iso_week);

-- Core fact table: one row per (CL, reviewer). Reviewer = non-owner account
-- that cast a non-zero Code-Review vote and/or authored a published comment.
CREATE TABLE IF NOT EXISTS reviews (
  host            TEXT    NOT NULL,
  change_number   INTEGER NOT NULL,
  account_id      INTEGER NOT NULL,
  review_comments INTEGER NOT NULL DEFAULT 0, -- human comments, inline + patchset-level
  review_chars    INTEGER NOT NULL DEFAULT 0, -- chars of those, quoted '> ' lines removed
  ai_comments     INTEGER NOT NULL DEFAULT 0, -- excluded: is_ai or autogenerated tag
  post_merge_comments INTEGER NOT NULL DEFAULT 0, -- subset of review_comments posted after closed_at
  voted_cr        INTEGER,                    -- final Code-Review vote, NULL = none
  is_owner        INTEGER,                    -- 1/0/NULL(unknown, not yet computed)
  owner_source    TEXT,
  PRIMARY KEY (host, change_number, account_id)
) STRICT, WITHOUT ROWID;
CREATE INDEX IF NOT EXISTS reviews_account ON reviews(host, account_id);

CREATE VIEW IF NOT EXISTS reviews_v AS
SELECT r.change_number, a.email AS reviewer_email, r.review_comments,
       r.review_chars, r.is_owner, r.voted_cr, a.is_bot,
       c.status, c.closed_at, c.iso_week, c.project, c.branch
FROM reviews r
JOIN changes c ON c.host = r.host AND c.change_number = r.change_number
JOIN accounts a ON a.host = r.host AND a.account_id = r.account_id;
"""


def now_iso():
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def connect(path, schema):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    db = sqlite3.connect(path)
    db.execute("PRAGMA journal_mode=WAL")
    db.executescript(schema)
    return db


def open_raw(data_dir=DATA_DIR):
    return connect(os.path.join(data_dir, "raw.sqlite"), RAW_SCHEMA)


def open_cosh(data_dir=DATA_DIR):
    return connect(os.path.join(data_dir, "cosh.sqlite"), COSH_SCHEMA)


def put_response(raw, host, kind, key, url, status, body):
    data = body.encode("utf-8")
    raw.execute(
        """INSERT INTO responses VALUES (?,?,?,?,?,?,?,?)
           ON CONFLICT(host, kind, key) DO UPDATE SET url=excluded.url,
             fetched_at=excluded.fetched_at, http_status=excluded.http_status,
             body_zlib=excluded.body_zlib, body_sha256=excluded.body_sha256""",
        (host, kind, key, url, now_iso(), status, zlib.compress(data, 9),
         hashlib.sha256(data).hexdigest()))


def get_response(raw, host, kind, key):
    row = raw.execute(
        "SELECT http_status, body_zlib FROM responses WHERE host=? AND kind=? AND key=?",
        (host, kind, key)).fetchone()
    if row is None:
        return None
    return row[0], zlib.decompress(row[1]).decode("utf-8")
